"""Write site/maps.js from fragsubs/callouts.py, so the website shows the same
callouts the app uses. Run after changing callouts.py:

    python scripts/make_site_maps.py

tests/test_site.py fails when site/maps.js is out of date.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fragsubs.callouts import MAPS  # noqa: E402

TARGET = ROOT / "site" / "maps.js"


def render() -> str:
    maps = [{"key": m.key, "name": m.name, "callouts": list(m.callouts)}
            for m in sorted(MAPS.values(), key=lambda m: m.name)]
    body = json.dumps(maps, ensure_ascii=False, indent=1)
    return ("// Generated by scripts/make_site_maps.py from fragsubs/callouts.py. Don't edit by hand.\n"
            f"window.FRAGSUBS_MAPS = {body};\n")


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET}")
